        wrap.addEventListener('pointerdown', e => {
      if (e.button !== 0) return;
  
      C.drag = {
          x: e.clientX,
          y: e.clientY,
          tx: C.tx,
          lx: e.clientX,
          t: performance.now(),
          moved: false,
          id: e.pointerId
      };
      try {
          wrap.setPointerCapture(e.pointerId);
      } catch (_) {}
  
      dc.classList.add('is-down');
  });
  
  window.addEventListener('pointermove', e => {
      if (!COARSE.matches) {
          dcX = e.clientX;
          dcY = e.clientY;
      }
  
      if (!C.drag) return;
  
      const dx = e.clientX - C.drag.x;
      const dy = e.clientY - C.drag.y;
  
      if (!C.drag.moved) {
          if (Math.abs(dx) < 6 && Math.abs(dy) < 6) return;
          if (Math.abs(dy) > Math.abs(dx)) {
              C.drag = null;
              dc.classList.remove('is-down');
  
              try {
                  wrap.releasePointerCapture(e.pointerId);
              } catch (_) {}
  
              return;
          }
  
          C.drag.moved = true;
          e.preventDefault();
      }
  
      if (!C.drag.moved) return;
  
      const now = performance.now();
  
      C.vel =
          (e.clientX - C.drag.lx) /
          Math.max(1, now - C.drag.t);
  
      C.drag.lx = e.clientX;
      C.drag.t = now;
  
      let t = C.drag.tx + dx;
  
      if (t > 0) {
          t *= 0.35;
      }
  
      if (t < C.min) {
          t = C.min + (t - C.min) * 0.35;
      }
  
      C.tx = t;
  });
  
  const endDrag = e => {
      if (!C.drag) return;
  
      dc.classList.remove('is-down');
  
      if (C.drag.moved) {
          suppressCardClick = true;
  
          const proj = C.tx + C.vel * 260;
  
          snapTo(Math.round(-proj / C.step));
      }
  
      try {
          if (e?.pointerId != null) {
              wrap.releasePointerCapture(e.pointerId);
          }
      } catch (_) {}
  
      C.drag = null;
  };
  
  window.addEventListener('pointerup', endDrag);
  window.addEventListener('pointercancel', endDrag);
      </script>